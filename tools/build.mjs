#!/usr/bin/env node
// Bundles the plugin's runtime scripts with esbuild. The outputs are committed, so a plugin
// installed from the marketplace needs nothing but `node` (no npm install).
//
//   node tools/build.mjs           write plugins/technocore/scripts/{technocore-watch,hooks}.mjs
//   node tools/build.mjs --check   fail if the committed bundles differ from a fresh build
//
// Sources:
//   technocore-watch.mjs  <- src/watch-cli.mjs + technocore-watch-core src/cli/main.ts (the core CLI, unmodified)
//   hooks.mjs             <- src/hooks.mjs (+ the pure protocol/state modules it imports from the core)
//
// The core checkout is found at $TECHNOCORE_WATCH_CORE or ../technocore-watch-core.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

export function findCore() {
  const candidates = [process.env.TECHNOCORE_WATCH_CORE, resolve(repo, '..', 'technocore-watch-core')].filter(Boolean);
  for (const c of candidates) {
    if (existsSync(join(c, 'src', 'cli', 'main.ts')) && existsSync(join(c, 'package.json'))) return resolve(c);
  }
  return null;
}

function coreProvenance(core) {
  const pkg = JSON.parse(readFileSync(join(core, 'package.json'), 'utf8'));
  let commit = 'unknown';
  let dirty = false;
  try {
    commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: core, encoding: 'utf8' }).trim();
    dirty = execFileSync('git', ['status', '--porcelain', '--', 'src', 'package.json'], { cwd: core, encoding: 'utf8' }).trim() !== '';
  } catch {
    // not a git checkout
  }
  return { name: pkg.name, version: pkg.version, commit: dirty ? `${commit}+dirty` : commit };
}

function banner(what, prov) {
  return [
    `// ${what}`,
    '// Unofficial community integration — not affiliated with or endorsed by FLOP Labs.',
    `// GENERATED by tools/build.mjs with esbuild ${esbuild.version} from ${prov.name} ${prov.version} @ ${prov.commit}.`,
    '// Do not edit: change the source and rebuild. technocore-watch-core is MIT licensed (see NOTICE).',
  ].join('\n');
}

const coreAlias = (core) => ({
  name: 'core-alias',
  setup(build) {
    build.onResolve({ filter: /^@core\// }, (args) => ({ path: join(core, 'src', args.path.slice('@core/'.length)) }));
  },
});

async function bundle(core, prov) {
  const common = {
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    charset: 'utf8',
    legalComments: 'inline',
    write: false,
    logLevel: 'silent',
    absWorkingDir: repo,
  };
  const cli = await esbuild.build({
    ...common,
    entryPoints: [join(repo, 'src', 'watch-cli.mjs')],
    outfile: 'plugins/technocore/scripts/technocore-watch.mjs',
    plugins: [coreAlias(core)],
    // The core CLI runs itself when its own file is the entry point (isEntrypoint compares
    // import.meta.url with argv[1]). Bundled, that file is this wrapper, so neutralise the check:
    // the wrapper calls main() exactly once. import.meta.url has no other use in the core.
    define: { 'import.meta.url': '"data:,technocore-watch-core-bundled"' },
    banner: { js: `#!/usr/bin/env node\n${banner('technocore-watch CLI (technocore-watch-core src/cli/main.ts, unmodified, + src/watch-cli.mjs plugin defaults)', prov)}` },
  });
  const hooks = await esbuild.build({
    ...common,
    entryPoints: [join(repo, 'src', 'hooks.mjs')],
    outfile: 'plugins/technocore/scripts/hooks.mjs',
    plugins: [coreAlias(core)],
    banner: { js: banner('technocore Claude Code hooks (bundled src/hooks.mjs)', prov) },
  });
  // esbuild embeds absolute source paths only in comments for files outside absWorkingDir;
  // normalise them so the output does not depend on where the checkout lives.
  const rel = relative(repo, core).split(sep).join('/');
  const norm = (text) => text.split(core).join('technocore-watch-core').split(`// ${rel}/`).join('// technocore-watch-core/');
  return [
    { path: join(repo, 'plugins/technocore/scripts/technocore-watch.mjs'), text: norm(cli.outputFiles[0].text), mode: 0o755 },
    { path: join(repo, 'plugins/technocore/scripts/hooks.mjs'), text: norm(hooks.outputFiles[0].text), mode: 0o644 },
  ];
}

async function main() {
  const core = findCore();
  if (!core) {
    console.error('build: technocore-watch-core checkout not found (set TECHNOCORE_WATCH_CORE or place it at ../technocore-watch-core)');
    process.exit(2);
  }
  const prov = coreProvenance(core);
  const outputs = await bundle(core, prov);
  if (check) {
    let stale = 0;
    for (const o of outputs) {
      const current = existsSync(o.path) ? readFileSync(o.path, 'utf8') : null;
      if (current !== o.text) {
        console.error(`build --check: ${o.path.slice(repo.length + 1)} is stale; run \`npm run build\` and commit it`);
        stale++;
      }
    }
    if (stale) process.exit(1);
    console.log(`build --check: bundles are fresh (${prov.name} @ ${prov.commit})`);
    return;
  }
  if (prov.commit.endsWith('+dirty')) console.warn('build: warning: the core checkout has uncommitted changes in src/');
  for (const o of outputs) {
    writeFileSync(o.path, o.text);
    chmodSync(o.path, o.mode);
    console.log(`build: wrote ${o.path.slice(repo.length + 1)} (${o.text.length} chars)`);
  }
}

main().catch((e) => {
  console.error(`build: ${e.message ?? e}`);
  process.exit(1);
});
